//! Render a Command model as fish, bash and zsh completion scripts.
//!
//! Help text is untrusted and these files get sourced into an interactive shell,
//! so every name is validated and every description is quoted for the target shell.

use crate::model::{Command, Opt};
use crate::re;
use crate::util::*;
use crate::VERSION;

pub fn token_ok(s: &str) -> bool {
    is_match(re!(r"^[A-Za-z0-9_][\w.:@+,=%/-]*$"), s)
}

pub fn ident(name: &str) -> String {
    let mut h = sha1_smol::Sha1::new();
    h.update(name.as_bytes());
    let hex = h.digest().to_string();
    format!("{}_{}", replace_all(re!(r"\W"), name, "_"), &hex[..6])
}

pub fn clean_desc(s: &str) -> String {
    let s = replace_all(re!(r"[\x00-\x1f\x7f]"), s, " ");
    take_chars(s.trim(), 100)
}

/// Like Command::walk, but drops any subtree whose name is not a plain token.
pub fn safe_walk(cmd: &Command) -> Vec<(Vec<String>, &Command)> {
    let mut out = vec![];
    fn go<'a>(c: &'a Command, path: Vec<String>, out: &mut Vec<(Vec<String>, &'a Command)>) {
        out.push((path.clone(), c));
        for (n, s) in &c.subcommands {
            if token_ok(n) && !n.contains('/') {
                let mut p = path.clone();
                p.push(n.clone());
                go(s, p, out);
            }
        }
    }
    go(cmd, vec![], &mut out);
    out
}

fn check_name(name: &str) -> Result<(), String> {
    if !token_ok(name) || name.contains('/') {
        return Err(format!("refusing to render completions for unsafe name {name:?}"));
    }
    Ok(())
}

fn fish_kind(kind: &str) -> Option<&'static str> {
    Some(match kind {
        "dir" => "-xa '(__fish_complete_directories (commandline -ct))'",
        "user" => "-xa '(__fish_complete_users)'",
        "group" => "-xa '(__fish_complete_groups)'",
        "host" => "-xa '(__fish_print_hostnames)'",
        "pid" => "-xa '(__fish_complete_pids)'",
        "command" => "-xa '(__fish_complete_command)'",
        "number" => "-x",
        "file" => "-rF",
        _ => return None,
    })
}

fn sources(cmd: &Command) -> String {
    if cmd.sources.is_empty() { "unknown".into() } else { cmd.sources.join(", ") }
}

pub fn fish(cmd: &Command) -> Result<String, String> {
    let name = &cmd.name;
    check_name(name)?;
    let cid = ident(name);
    let mut out = vec![
        format!("# Generated by complete-me {VERSION} from: {}.", sources(cmd)),
        format!("# Regenerate: complete-me gen --force {name}    Remove: complete-me forget {name}"),
    ];
    let walk = safe_walk(cmd);
    let (mut tree, mut aliases, mut argopts) = (vec![], vec![], Vec::<String>::new());
    for (path, node) in &walk {
        tree.push(path.join(" "));
        for a in &node.aliases {
            if token_ok(a) {
                let mut p = path[..path.len().saturating_sub(1)].to_vec();
                p.push(a.clone());
                aliases.push(format!("{}={}", p.join(" "), path.last().cloned().unwrap_or_default()));
            }
        }
        for o in &node.options {
            if o.arg.is_some() && !o.arg_optional {
                for f in o.flags() {
                    if token_ok(f.trim_start_matches('-')) && !argopts.contains(&f) {
                        argopts.push(f);
                    }
                }
            }
        }
    }
    let join_fq = |v: &[String]| v.iter().map(|t| fq(t)).collect::<Vec<_>>().join(" ");
    out.push(format!("set -g __cm_tree_{cid} {}", join_fq(&tree)));
    out.push(format!("set -g __cm_alias_{cid} {}", join_fq(&aliases)));
    out.push(format!("set -g __cm_argopts_{cid} {}", join_fq(&argopts)));

    let mut vfn = 0;
    // fish only autosuggests (grey text) from completions with no condition and no command
    // substitution, so flat commands get plain static lines and inline enum values.
    let flat = cmd.subcommands.is_empty();
    for (path, node) in &walk {
        let cond = fq(&format!("__complete_me_at {cid}{}", path.iter().map(|p| format!(" {p}")).collect::<String>()));
        let base = if flat { format!("complete -c {name}") } else { format!("complete -c {name} -n {cond}") };
        for (sub_name, sub) in &node.subcommands {
            if !token_ok(sub_name) {
                continue;
            }
            let d = clean_desc(&sub.desc);
            let d = if d.is_empty() { "subcommand".to_string() } else { d };
            out.push(format!("{base} -f -a {} -d {}", fq(sub_name), fq(&d)));
            for a in &sub.aliases {
                if token_ok(a) {
                    out.push(format!("{base} -f -a {} -d {}", fq(a), fq(&format!("alias for {sub_name}"))));
                }
            }
        }
        let mut words = vec![name.clone()];
        words.extend(path.iter().cloned());
        let hist = fq(&format!("(__complete_me_hist_args {})", words.join(" ")));
        if !node.subcommands.is_empty() && !node.takes_files {
            out.push(format!("{base} -f"));
        } else if node.takes_files {
            out.push(format!("{base} -k -a {hist}"));
        } else {
            out.push(format!("{base} -f -k -a {hist}"));
        }
        for o in &node.options {
            let mut parts = vec![];
            for s in &o.shorts {
                if is_match(re!(r"^[A-Za-z0-9?#]$"), s) {
                    parts.push(format!("-s {}", fq(s)));
                }
            }
            for l in &o.longs {
                if token_ok(l) {
                    parts.push(format!("-l {}", fq(l)));
                }
            }
            for old in &o.olds {
                if token_ok(old) {
                    parts.push(format!("-o {}", fq(old)));
                }
            }
            if parts.is_empty() {
                continue;
            }
            let parts = parts.join(" ");
            let mut line = format!("{base} {parts}");
            if !o.desc.is_empty() {
                line += &format!(" -d {}", fq(&clean_desc(&o.desc)));
            }
            if !o.values.is_empty() && flat {
                out.push(format!("{line} -x"));
                for (v, d) in &o.values {
                    if token_ok(v) {
                        let mut l = format!("{base} {parts} -x -a {}", fq(v));
                        if !d.is_empty() {
                            l += &format!(" -d {}", fq(&clean_desc(d)));
                        }
                        out.push(l);
                    }
                }
                continue;
            }
            if !o.values.is_empty() {
                vfn += 1;
                let f = format!("__cm_v_{cid}_{vfn}");
                let rows: Vec<String> = o
                    .values
                    .iter()
                    .filter(|(v, _)| token_ok(v))
                    .map(|(v, d)| format!("{} {}", fq(v), fq(&clean_desc(d))))
                    .collect();
                out.push(format!("function {f}; printf '%s\\t%s\\n' {}; end", rows.join(" ")));
                line += &format!(" -x -a '({f})'");
            } else if o.arg.is_some() {
                let flag = &o.flags()[0];
                let hist = format!("(__complete_me_hist_optvals {name} {flag})");
                match fish_kind(&o.kind) {
                    None => line += &format!(" -r -a {}", fq(&hist)),
                    Some("-x") => line += &format!(" -x -a {}", fq(&hist)),
                    Some("-rF") => line += " -rF",
                    Some(k) => line += &format!(" {k}"),
                }
            }
            out.push(line);
        }
    }
    Ok(out.join("\n") + "\n")
}

pub fn bash(cmd: &Command) -> Result<String, String> {
    let name = &cmd.name;
    check_name(name)?;
    let f = format!("_complete_me_{}", replace_all(re!(r"\W"), name, "_"));
    let walk = safe_walk(cmd);
    let (mut cases_words, mut cases_vals) = (vec![], vec![]);
    for (path, node) in &walk {
        let key = path.join(" ");
        let mut words: Vec<String> = node.subcommands.keys().cloned().collect();
        for s in node.subcommands.values() {
            words.extend(s.aliases.iter().cloned());
        }
        for o in &node.options {
            words.extend(o.flags().into_iter().filter(|f| token_ok(f.trim_start_matches('-'))));
            if !o.values.is_empty() {
                let vals: Vec<&str> = o.values.iter().filter(|(v, _)| token_ok(v)).map(|(v, _)| v.as_str()).collect();
                for fl in o.flags() {
                    cases_vals.push(format!(
                        "        {}) COMPREPLY=($(compgen -W {} -- \"$cur\")); return;;",
                        sq(&format!("{key}|{fl}")),
                        sq(&vals.join(" "))
                    ));
                }
            }
        }
        let files = if node.takes_files && node.subcommands.is_empty() { "1" } else { "0" };
        let ws: Vec<String> = words.into_iter().filter(|w| token_ok(w.trim_start_matches('-'))).collect();
        cases_words.push(format!("        {}) words={}; files={files};;", sq(&key), sq(&ws.join(" "))));
    }
    let tree: Vec<String> = walk.iter().filter(|(p, _)| !p.is_empty()).map(|(p, _)| sq(&p.join(" "))).collect();
    let vals = if cases_vals.is_empty() { "        __none__) ;;".to_string() } else { cases_vals.join("\n") };
    Ok(format!(
        r#"# Generated by complete-me {VERSION} from: {src}.
{f}() {{
    local cur="${{COMP_WORDS[COMP_CWORD]}}" prev="${{COMP_WORDS[COMP_CWORD-1]}}"
    local path="" i w words files
    local -a tree=({tree})
    for ((i = 1; i < COMP_CWORD; i++)); do
        w="${{COMP_WORDS[i]}}"
        [[ $w == -* ]] && continue
        local cand="${{path:+$path }}$w" t found=0
        for t in "${{tree[@]}}"; do [[ $t == "$cand" ]] && found=1 && break; done
        ((found)) && path="$cand" || break
    done
    case "$path|$prev" in
{vals}
    esac
    case "$path" in
{words}
        *) words=""; files=1;;
    esac
    COMPREPLY=($(compgen -W "$words" -- "$cur"))
    if ((files)) && [[ $cur != -* ]]; then
        COMPREPLY+=($(compgen -f -- "$cur"))
    fi
}}
complete -o bashdefault -o default -F {f} {name}
"#,
        src = cmd.sources.join(", "),
        tree = tree.join(" "),
        words = cases_words.join("\n"),
    ))
}

// ---------------------------------------------------------------- zsh

/// Escape text for the inside of an _arguments `[description]`.
fn zdesc(s: &str) -> String {
    clean_desc(s).replace('\\', "\\\\").replace('[', "\\[").replace(']', "\\]")
}

/// Escape text for an _arguments message / value list.
fn zcolon(s: &str) -> String {
    s.replace('\\', "\\\\").replace(':', "\\:")
}

fn zsh_action(o: &Opt) -> String {
    if !o.values.is_empty() {
        let vals: Vec<String> = o.values.iter().filter(|(v, _)| token_ok(v)).map(|(v, d)| {
            if d.is_empty() { zcolon(v) } else { format!("{}\\:{}", zcolon(v).replace(' ', "\\ "), zcolon(&clean_desc(d)).replace(' ', "\\ ")) }
        }).collect();
        if o.values.iter().any(|(_, d)| !d.is_empty()) {
            return format!("(({}))", vals.join(" "));
        }
        return format!("({})", vals.join(" "));
    }
    match o.kind.as_str() {
        "file" => "_files".into(),
        "dir" => "_files -/".into(),
        "user" => "_users".into(),
        "group" => "_groups".into(),
        "host" => "_hosts".into(),
        "pid" => "_pids".into(),
        "command" => "_command_names -e".into(),
        "number" => " ".into(),
        _ => "_default".into(),
    }
}

fn zsh_spec(o: &Opt) -> Vec<String> {
    let flags: Vec<String> = o.flags().into_iter().filter(|f| token_ok(f.trim_start_matches('-')) && !f.contains('=')).collect();
    if flags.is_empty() {
        return vec![];
    }
    let excl = if flags.len() > 1 { format!("({})", flags.join(" ")) } else { String::new() };
    let desc = format!("[{}]", zdesc(&o.desc));
    flags
        .iter()
        .map(|f| {
            let mut spec = format!("{excl}{f}");
            if let Some(arg) = &o.arg {
                // --long= accepts --long=x and --long x; -s+ accepts -sx and -s x
                if f.starts_with("--") {
                    spec.push('=');
                } else {
                    spec.push('+');
                }
                spec += &desc;
                let msg = zcolon(arg.trim_matches(|c| "<>[]=".contains(c)));
                let msg = if msg.is_empty() { "value".to_string() } else { msg.to_lowercase() };
                spec += &format!(":{msg}:{}", zsh_action(o));
            } else {
                spec += &desc;
            }
            sq(&spec)
        })
        .collect()
}

pub fn zsh(cmd: &Command) -> Result<String, String> {
    let name = &cmd.name;
    check_name(name)?;
    let f = format!("_complete_me_{}", replace_all(re!(r"\W"), name, "_"));
    let walk = safe_walk(cmd);
    let tree: Vec<String> = walk.iter().filter(|(p, _)| !p.is_empty()).map(|(p, _)| sq(&p.join(" "))).collect();
    let mut cases = vec![];
    for (path, node) in &walk {
        let key = path.join(" ");
        let mut specs = vec![];
        for o in &node.options {
            specs.extend(zsh_spec(o));
        }
        let mut subs = vec![];
        for (n, s) in &node.subcommands {
            if !token_ok(n) {
                continue;
            }
            let d = clean_desc(&s.desc);
            subs.push(sq(&format!("{}:{}", zcolon(n), if d.is_empty() { "subcommand".into() } else { d })));
            for a in &s.aliases {
                if token_ok(a) {
                    subs.push(sq(&format!("{}:alias for {}", zcolon(a), n)));
                }
            }
        }
        let files = node.takes_files;
        let mut body = String::new();
        body += &format!("        {})\n", sq(&key));
        body += &format!("            subs=({})\n", subs.join(" "));
        body += &format!("            files={}\n", if files { 1 } else { 0 });
        body += "            _arguments -s -S : \\\n";
        for s in &specs {
            body += &format!("                {s} \\\n");
        }
        body += "                '*: :->rest' && ret=0\n";
        body += "            ;;";
        cases.push(body);
    }
    Ok(format!(
        r#"# Generated by complete-me {VERSION} from: {src}.
# Regenerate: complete-me gen --force {name}    Remove: complete-me forget {name}
{f}() {{
    local -a tree subs
    tree=({tree})
    local cpath="" w cand i files=1 ret=1
    local context state state_descr line
    typeset -A opt_args
    for (( i = 2; i < CURRENT; i++ )); do
        w=${{words[i]}}
        [[ $w == -* ]] && continue
        cand="${{cpath:+$cpath }}$w"
        if (( ${{tree[(Ie)$cand]}} )); then cpath=$cand; else break; fi
    done
    case $cpath in
{cases}
        *)
            _default && ret=0
            return ret
            ;;
    esac
    if [[ $state == rest ]]; then
        (( ${{#subs}} )) && _describe -t commands 'subcommand' subs && ret=0
        (( files )) && _files && ret=0
    fi
    return ret
}}
compdef {f} {name}
"#,
        src = sources(cmd),
        tree = tree.join(" "),
        cases = cases.join("\n"),
    ))
}
